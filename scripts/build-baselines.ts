/* ------------------------------------------------------------- helpers */

async function writeJsonAtomic(path: string, data: unknown) {
  await mkdir(dirname(path), { recursive: true });
  const tmp = `${path}.tmp`;
  await writeFile(tmp, `${JSON.stringify(data, null, 2)}\n`, "utf8");
  await rename(tmp, path);
}

async function readJson<T>(path: string): Promise<T | null> {
  try {
    return JSON.parse(await readFile(path, "utf8")) as T;
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "ENOENT") return null;
    throw err;
  }
}

type Manifest = Record<string, { source: string; fetchedAt: string }>;

/** Collects warnings for one output file and echoes them to the console. */
function warnings() {
  const list: string[] = [];
  return {
    list,
    warn(msg: string) {
      list.push(msg);
      console.warn(`    ! ${msg}`);
    },
  };
}

/* ----------------------------------------------------- baselines.json */

const OSDR_SOURCE = "NASA OSDR OSD-575";
const OSDR_NOTE = "Inspiration4 crew, n=4, pre/post-flight only";
const IMMEDIATE_RETURN = "R+1";

/** The analytes we keep. eGFR (race-based) and the BUN/creatinine ratio are excluded on purpose. */
const ANALYTES = [
  {
    key: "glucose",
    analyte: "Glucose",
    prefix: "glucose",
    analyte_note: "Fasting status not stated in source (OSD-575 ISA metadata checked).",
  },
  { key: "calcium", analyte: "Calcium", prefix: "calcium" },
  { key: "sodium", analyte: "Sodium", prefix: "sodium" },
  { key: "potassium", analyte: "Potassium", prefix: "potassium" },
  { key: "bun", analyte: "BUN (urea nitrogen)", prefix: "urea_nitrogen_bun" },
  { key: "creatinine", analyte: "Creatinine", prefix: "creatinine" },
] as const;

/** Lab values: 3 decimals is finer than any source value (max 2 dp). */
const r3 = (v: number) => roundTo(v, 3);
const statsOut = (xs: number[]) => {
  const s = summarize(xs);
  return { min: r3(s.min), max: r3(s.max), mean: r3(s.mean), median: r3(s.median), n: s.n };
};

function parseOsdrCsv(csv: string) {
  const text = csv.replace(/^﻿/, "").trim();
  if (text.includes('"')) throw new Error(`${OSDR.out}: quoted CSV fields are not supported`);
  const [headerLine, ...lines] = text.split(/\r?\n/);
  const header = headerLine.split(",");
  const rows = lines.map((line) => {
    const cells = line.split(",");
    if (cells.length !== header.length) throw new Error(`${OSDR.out}: row has ${cells.length} cells, header ${header.length}`);
    const { crew, timepoint } = parseSampleName(cells[0]);
    return { crew, timepoint, cell: (col: string) => cells[header.indexOf(col)] };
  });
  return { header, rows };
}

async function buildBaselines(manifest: Manifest) {
  const w = warnings();
  const { header, rows } = parseOsdrCsv(await readFile(OSDR.out, "utf8"));
  const common = { source: OSDR_SOURCE, url: OSDR.filesApi, note: OSDR_NOTE };

  const timepoints = [...new Map(rows.map((r) => [r.timepoint.label, r.timepoint])).values()].sort(compareTimepoints);
  const crews = [...new Set(rows.map((r) => r.crew))].sort();
  const preflight = timepoints.filter((t) => t.phase === "pre-flight").map((t) => t.label);
  if (!timepoints.some((t) => t.label === IMMEDIATE_RETURN)) throw new Error(`No ${IMMEDIATE_RETURN} samples in ${OSDR.out}`);

  const analytes = [];
  const entries = [];
  const preflightBaseline = [];
  const immediateReturn = [];
  const perCrew = [];

  for (const a of ANALYTES) {
    const cols = resolveAnalyteColumns(header, a.prefix);
    const values = rows.flatMap((r) => {
      const v = parseLabNumber(r.cell(cols.value));
      if (v === null) w.warn(`${a.analyte}: missing value for ${r.crew} ${r.timepoint.label}; skipped`);
      return v === null ? [] : [{ crew: r.crew, tp: r.timepoint, v }];
    });
    const pick = (keep: (x: (typeof values)[number]) => boolean) => values.filter(keep).map((x) => x.v);

    // Lab reference range: most common (min, max) pair across rows.
    const ranges = rows.map((r) => ({
      min: cols.rangeMin ? parseLabNumber(r.cell(cols.rangeMin)) : null,
      max: cols.rangeMax ? parseLabNumber(r.cell(cols.rangeMax)) : null,
    }));
    const range = mode(ranges, (x) => `${x.min}|${x.max}`);
    if (!cols.rangeMin || !cols.rangeMax) w.warn(`${a.analyte}: lab range column(s) not found`);
    if (range.distinct > 1) {
      w.warn(
        `${a.analyte}: lab range differs between rows (${range.distinct} variants); using the most common, ${range.value.min}–${range.value.max} (${range.count}/${rows.length} rows)`,
      );
    }
    const lab = { lab_range_min: range.value.min, lab_range_max: range.value.max };
    const head = { analyte: a.analyte, unit: cols.unit };
    const extra = "analyte_note" in a ? { analyte_note: a.analyte_note } : {};

    analytes.push({ key: a.key, ...head, column: cols.value, ...lab, ...extra });

    for (const tp of timepoints) {
      const xs = pick((x) => x.tp.label === tp.label);
      if (xs.length === 0) continue;
      entries.push({
        ...head,
        timepoint: tp.label,
        phase: tp.phase,
        days_from_event: tp.days_from_event,
        relative_to: tp.relative_to,
        ...statsOut(xs),
        ...lab,
        ...extra,
        ...common,
      });
    }

    const pre = pick((x) => x.tp.phase === "pre-flight");
    const preStats = statsOut(pre);
    const preSd = sampleSd(pre);
    preflightBaseline.push({
      ...head,
      timepoints: preflight,
      ...preStats,
      sd: preSd === null ? null : r3(preSd),
      ...lab,
      ...extra,
      ...common,
    });

    const ret = pick((x) => x.tp.label === IMMEDIATE_RETURN);
    const retSd = sampleSd(ret);
    const retStats = summarize(ret);
    const change = changeFrom(retStats.mean, summarize(pre).mean);
    immediateReturn.push({
      ...head,
      timepoints: [IMMEDIATE_RETURN],
      ...statsOut(ret),
      sd: retSd === null ? null : r3(retSd),
      change_from_preflight_mean: {
        absolute: r3(change.absolute),
        percent: change.percent === null ? null : roundTo(change.percent, 1),
      },
      ...lab,
      ...extra,
      ...common,
    });

    for (const crew of crews) {
      const xs = pick((x) => x.crew === crew && x.tp.phase === "pre-flight");
      if (xs.length === 0) continue;
      if (xs.length !== preflight.length) w.warn(`${a.analyte}: ${crew} has ${xs.length}/${preflight.length} pre-flight samples`);
      // Ranges vary by crew member (the lab appears to use sex/age-specific
      // ranges), so a personal baseline carries that crew member's own range.
      const own = mode(
        rows.filter((r) => r.crew === crew && r.timepoint.phase === "pre-flight").map((r) => ({
          min: cols.rangeMin ? parseLabNumber(r.cell(cols.rangeMin)) : null,
          max: cols.rangeMax ? parseLabNumber(r.cell(cols.rangeMax)) : null,
        })),
        (x) => `${x.min}|${x.max}`,
      );
      perCrew.push({
        crew,
        ...head,
        timepoints: preflight,
        ...statsOut(xs),
        lab_range_min: own.value.min,
        lab_range_max: own.value.max,
        lab_range_scope: "this crew member's pre-flight samples",
        ...extra,
        ...common,
      });
    }
  }

  const out = {
    generated_at: new Date().toISOString(),
    dataset: "OSD-575 · Inspiration4 Comprehensive Metabolic Panel (TRANSFORMED CSV)",
    source: OSDR_SOURCE,
    url: OSDR.filesApi,
    source_file_url: manifest[OSDR.out]?.source ?? null,
    cached_file: OSDR.out,
    note: OSDR_NOTE,
    crew: crews,
    timepoints: timepoints.map((t) => ({ timepoint: t.label, phase: t.phase, days_from_event: t.days_from_event, relative_to: t.relative_to })),
    inflight_samples: 0,
    inflight_note:
      "Inspiration4 was a 3-day flight (September 2021). Blood was drawn only before launch (L-92, L-44, L-3) and after return (R+1, R+45, R+82, R+194), so OSD-575 contains no in-flight metabolic panel values.",
    method:
      "Per time point: min, max, mean, median and n across crew. Pooled pre-flight baseline uses all L- samples; immediate return is R+1. SD is the sample standard deviation (n − 1). Change from baseline = R+1 mean − pre-flight mean, and as % of the pre-flight mean. Lab range = most common range in the file (per_crew_preflight uses each crew member's own pre-flight range, because ranges vary by crew member). Values rounded to 3 decimals, percentages to 1.",
    excluded: ["eGFR (African American and non-African American columns; race-based)", "BUN-to-creatinine ratio"],
    analytes,
    entries,
    pooled: { preflight_baseline: preflightBaseline, immediate_return: immediateReturn },
    per_crew_preflight: perCrew,
    warnings: w.list,
  };
  await writeJsonAtomic(DERIVED.baselines, out);
  return `${entries.length} time-point entries, ${perCrew.length} per-crew baselines, ${w.list.length} warning(s)`;
}

/* ---------------------------------------- radiation-environments.json */

/** Dose values: 4 significant figures. */
const sig4 = (v: number) => Number(v.toPrecision(4));

function parseRadlabCsv(csv: string, file: string) {
  const [headerLine, ...lines] = csv.trim().split(/\r?\n/);
  const cols = headerLine.split(",");
  const at = (name: string) => cols.indexOf(name);
  const [iT, iId, iAbs, iEq] = [
    at("timestamp"),
    at("instrument_id"),
    at("absorbed_dose_rate_uGy_h"),
    at("dose_equivalent_rate_uSv_h"),
  ];
  if (iT < 0 || iAbs < 0) throw new Error(`${file}: unexpected header ${headerLine}`);
  const rows = lines.map((l) => l.split(","));
  const toSamples = (i: number): DoseSample[] =>
    rows.map((c) => ({ day: c[iT].slice(0, 10), detector: c[iId] || "default", rate: i < 0 ? null : parseLabNumber(c[i]) }));
  return {
    rows: rows.length,
    detectors: [...new Set(rows.map((c) => c[iId] || "default"))].sort(),
    absorbed: toSamples(iAbs),
    equivalent: toSamples(iEq),
  };
}

function doseStats(days: { day: string; dose: number }[]) {
  const s = summarize(days.map((d) => d.dose));
  return { mean: sig4(s.mean), median: sig4(s.median), min: sig4(s.min), max: sig4(s.max) };
}

/** Absorbed dose or measured dose equivalent from one cached RadLab file. */
async function radlabSeries(s: RadlabSource) {
  const parsed = parseRadlabCsv(await readFile(s.out, "utf8"), s.out);
  const days = dailyDoses(s.role === "absorbed" ? parsed.absorbed : parsed.equivalent);
  const field = s.role === "absorbed" ? "absorbed_dose_rate" : "dose_equivalent_rate";
  if (days.length === 0) throw new Error(`${s.id}: no complete days of ${field} in ${s.out}`);
  return {
    instrument: s.instrument,
    spacecraft: s.spacecraft,
    detectors: parsed.detectors,
    date_range: { start: days[0].day, end: days.at(-1)!.day },
    query_window_utc: { start: `${s.start}Z`, end: `${s.end}Z` },
    days_used: days.length,
    stats: doseStats(days),
    days,
    note: s.note,
    source: "NASA OSDR RadLab",
    api_url: radlabUrl(s),
    cached_file: s.out,
  };
}

async function buildRadiationEntry(def: RadiationEnvironmentDef) {
  const absorbedSrc = RADLAB_SOURCES.find((s) => s.environmentId === def.id && s.role === "absorbed");
  const measuredSrc = RADLAB_SOURCES.find((s) => s.environmentId === def.id && s.role === "dose_equivalent");
  const published = PUBLISHED_DOSE_EQUIVALENT.find((p) => p.environmentId === def.id);

  const abs = absorbedSrc ? await radlabSeries(absorbedSrc) : null;
  const measured = measuredSrc ? await radlabSeries(measuredSrc) : null;

  // Spike flag on the absorbed series (e.g. a solar particle event in the window).
  const biggest = (abs ? elevatedRuns(abs.days) : []).sort((x, y) => y.peak - x.peak)[0];
  const notable_event = biggest
    ? {
        start: biggest.start,
        end: biggest.end,
        peak_day: biggest.peak_day,
        peak_mGy: sig4(biggest.peak),
        threshold_mGy: sig4(biggest.threshold),
        description: `Likely solar particle event: daily absorbed dose above ${ELEVATED_DAY_FACTOR} × the window median. Not confirmed against an event catalogue.`,
      }
    : null;

  // Dose equivalent: measured by RadLab first, then a published value. Never estimated.
  const doseEquivalent = measured
    ? {
        basis: "measured" as const,
        mSv_per_day: measured.stats.mean,
        typical_mSv_per_day: measured.stats.median,
        min_daily_mSv: measured.stats.min,
        max_daily_mSv: measured.stats.max,
        instrument: measured.instrument,
        spacecraft: measured.spacecraft,
        date_range: measured.date_range,
        days_used: measured.days_used,
        daily: measured.days.map((d) => ({ date: d.day, mSv: sig4(d.dose) })),
        note: measured.note,
        source: measured.source,
        api_url: measured.api_url,
        cached_file: measured.cached_file,
      }
    : published
      ? {
          basis: "published" as const,
          mSv_per_day: published.mSv_per_day,
          uncertainty_mSv_per_day: published.uncertainty_mSv_per_day,
          scope: published.scope,
          citation: published.citation,
          quote: published.quote,
          verified_in: published.verified_in,
        }
      : null;

  if (!abs && !doseEquivalent) throw new Error(`${def.id}: no RadLab data and no published value`);
  const dose_type = abs
    ? doseEquivalent
      ? `absorbed dose (RadLab) and dose equivalent (${doseEquivalent.basis})`
      : "absorbed dose only"
    : `dose equivalent only (${doseEquivalent!.basis})`;

  return {
    id: def.id,
    environment: def.environment,
    location: def.location,
    instrument: abs?.instrument ?? null,
    spacecraft: abs?.spacecraft ?? null,
    detectors: abs?.detectors ?? [],
    date_range: abs?.date_range ?? null,
    query_window_utc: abs?.query_window_utc ?? null,
    days_used: abs?.days_used ?? 0,
    mGy_per_day: abs?.stats.mean ?? null,
    typical_mGy_per_day: abs?.stats.median ?? null,
    median_mGy_per_day: abs?.stats.median ?? null,
    min_daily_mGy: abs?.stats.min ?? null,
    max_daily_mGy: abs?.stats.max ?? null,
    mSv_per_day: doseEquivalent?.mSv_per_day ?? null,
    mSv_basis: doseEquivalent?.basis ?? null,
    dose_type,
    ...(abs ? {} : { absorbed_note: "No RadLab absorbed-dose data for this environment." }),
    ...(doseEquivalent
      ? {}
      : {
          dose_equivalent_note:
            "No measured dose equivalent in RadLab and no published value in the sources used, so mSv/day is null.",
        }),
    notable_event,
    daily: abs?.days.map((d) => ({ date: d.day, mGy: sig4(d.dose) })) ?? [],
    dose_equivalent: doseEquivalent,
    note: abs?.note ?? null,
    source: abs?.source ?? null,
    api_url: abs?.api_url ?? null,
    cached_file: abs?.cached_file ?? null,
  };
}

async function buildRadiation() {
  const environments = [];
  for (const def of RADIATION_ENVIRONMENTS) environments.push(await buildRadiationEntry(def));
  await writeJsonAtomic(DERIVED.radiation, {
    generated_at: new Date().toISOString(),
    source: "NASA OSDR RadLab, plus published dose-equivalent values where RadLab has none",
    docs: RADLAB_DOCS,
    method:
      'Per detector and UTC day: mean dose rate × 24 h ÷ 1000 (μGy/h → mGy/day; μSv/h → mSv/day). Detector-days with < 90% of that detector\'s busiest-day sample count are dropped; detectors are averaged per day. mGy_per_day is the mean of the days, typical_mGy_per_day (= median_mGy_per_day) their median, max_daily_mGy the highest day. notable_event flags consecutive days above 1.5 × the median. mSv_per_day is RadLab dose_equivalent_rate where it exists (basis "measured"), otherwise a value copied from a peer-reviewed paper (basis "published"). Cosmic Shield never applies a quality factor. 4 significant figures.',
    caveat:
      "Absorbed dose (mGy) is measured in each instrument's detector material and is not dose equivalent (mSv). Measured and published mSv values come from different instruments, years and solar conditions than the absorbed-dose windows.",
    not_available: [
      "MSL-RAD cruise data (Dec 2011 - Aug 2012) is not in RadLab, so Mars transit has no absorbed dose.",
      "IV-TEPC and TEPC are in RadLab (2014-2020) but their dose_equivalent_rate is empty, so ISS mSv/day comes from ALTEA-Survey.",
      "No dose equivalent for lunar orbit (CRaTER reports absorbed dose only).",
    ],
    environments,
  });
  return environments
    .map(
      (e) =>
        `\n    ${e.environment}: ${e.mGy_per_day ?? "-"} mGy/day (typical ${e.typical_mGy_per_day ?? "-"}, max ${e.max_daily_mGy ?? "-"}), ${e.mSv_per_day ?? "-"} mSv/day ${e.mSv_basis ?? ""}${e.notable_event ? ` [event ${e.notable_event.start}→${e.notable_event.end}]` : ""}`,
    )
    .join("");
}

/* ------------------------------------------------- space-weather.json */

const LATEST = 30;

interface DonkiCache {
  type: DonkiType;
  startDate: string;
  endDate: string;
  source: string;
  fetchedAt: string;
  count: number;
  events: Record<string, unknown>[];
}

async function buildSpaceWeather(manifest: Manifest) {
  const w = warnings();
  const feeds = [];
  const all: SpaceWeatherEvent[] = [];

  for (const type of DONKI.types) {
    const file = `${DONKI.outDir}/${type.toLowerCase()}.json`;
    const cache = await readJson<DonkiCache>(file);
    if (!cache) {
      w.warn(`${type}: no cached file (${file}); run npm run data:fetch -- --only=donki`);
      feeds.push({ type, status: "missing" as const, cached_file: file });
      continue;
    }
    const sourceUrl = manifest[file]?.source ?? cache.source;
    if (!manifest[file]) w.warn(`${type}: not in manifest.json; using the URL stored in ${file}`);
    let skipped = 0;
    for (const raw of cache.events) {
      try {
        all.push(simplifyDonkiEvent(type, raw));
      } catch {
        skipped++;
      }
    }
    if (skipped) w.warn(`${type}: ${skipped} event(s) without an id or start time skipped`);
    feeds.push({
      type,
      status: "ok" as const,
      source_url: sourceUrl,
      source_host: donkiHost(sourceUrl),
      fetched_at: manifest[file]?.fetchedAt ?? cache.fetchedAt,
      start_date: cache.startDate,
      end_date: cache.endDate,
      event_count: cache.events.length,
      cached_file: file,
    });
  }

  const fetched = feeds.flatMap((f) => (f.status === "ok" ? [f.fetched_at] : [])).sort();
  const events = latestEvents(all, LATEST);
  await writeJsonAtomic(DERIVED.spaceWeather, {
    generated_at: new Date().toISOString(),
    source: "NASA DONKI (Space Weather Database Of Notifications, Knowledge, Information)",
    /** Oldest fetch among the feeds, so the file never looks fresher than it is. */
    fetched_at: fetched[0] ?? null,
    feeds,
    total_events: all.length,
    note: `Newest first; the latest ${LATEST} across all feeds. class_or_intensity: flare class (FLR), CME speed type and speed from the most accurate analysis (CME), maximum Kp (GST), null for SEP.`,
    events,
    warnings: w.list,
  });
  return `${events.length} of ${all.length} events (${feeds.map((f) => `${f.type} ${f.status === "ok" ? f.event_count : "missing"}`).join(", ")}), ${w.list.length} warning(s)`;
}

/* ---------------------------------------------------------------- main */

async function main() {
  const manifest = (await readJson<Manifest>(MANIFEST)) ?? {};
  const steps: [string, () => Promise<string>][] = [
    [DERIVED.baselines, () => buildBaselines(manifest)],
    [DERIVED.radiation, buildRadiation],
    [DERIVED.spaceWeather, () => buildSpaceWeather(manifest)],
  ];

  let failures = 0;
  for (const [file, run] of steps) {
    console.log(`→ ${file}`);
    try {
      console.log(`  ✓ ${await run()}`);
      await mkdir(FIXTURES_DIR, { recursive: true });
      await copyFile(file, `${FIXTURES_DIR}/${basename(file)}`);
    } catch (err) {
      failures++;
      console.error(`  ✗ ${err instanceof Error ? err.message : String(err)}`);
    }
  }
  console.log(`\nFixtures copied to ${FIXTURES_DIR}/`);
  if (failures) {
    console.error(`${failures} file(s) failed; their previous derived and fixture copies were left in place.`);
    process.exitCode = 1;
  }
}

main().catch((err) => {
  console.error(err instanceof Error ? (err.stack ?? err.message) : err);
  process.exit(1);
});

